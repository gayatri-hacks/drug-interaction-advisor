import engine


def _rxnorm(name):
    return {"generic_name": name.lower(), "rxcui": "1", "status": "success", "summary": "RxNorm ok"}


def _fda(name):
    return {"found": False, "status": "not_found", "summary": "No label", "rxnorm": _rxnorm(name), "source_url": None}


def test_keyless_local_analysis_is_unknown_not_safe(monkeypatch):
    monkeypatch.delenv("OPENAI_API_KEY", raising=False)
    monkeypatch.setattr(engine, "rxnav_normalize", _rxnorm)
    monkeypatch.setattr(engine, "check_local_interactions", lambda drugs: {"interactions": [], "summary": "none"})
    monkeypatch.setattr(engine, "assess_patient_risk", lambda *args: {"risk_items": [], "allergy_conflicts": [], "beers_flags": [], "condition_warnings": [], "summary": "none"})
    monkeypatch.setattr(engine, "openfda_lookup", _fda)
    result = engine.run_analysis(30, [], [], [], "example", provider="local")
    assert result["risk_level"] == "UNKNOWN"
    assert "not evidence of safety" in result["final_answer"]
    assert "Generated by local rules" in result["final_answer"]


def test_provider_selection_and_missing_credentials(monkeypatch):
    assert engine.selected_provider("local") == "local"
    monkeypatch.delenv("OPENAI_API_KEY", raising=False)
    monkeypatch.delenv("GROQ_API_KEY", raising=False)
    for provider in ("openai", "groq"):
        try:
            engine.get_llm(provider)
        except engine.ProviderConfigurationError as exc:
            assert "not configured" in str(exc)
        else:
            raise AssertionError("Expected missing-credential error")


def test_known_high_risk_cannot_be_downgraded():
    interactions = {"interactions": [{"severity": "HIGH", "drug_a": "a", "drug_b": "b", "effect": "risk"}]}
    patient = {"allergy_conflicts": [], "condition_warnings": [], "beers_flags": []}
    assert engine._risk_level(interactions, patient) == "HIGH RISK"
